pub fn get_rs_blocks(type_number: i32, error_correct_level: QRErrorCorrectLevel) -> Vec<QRRSBlock> {
    let level_map = [1, 0, 3, 2];
    let level_index = level_map[error_correct_level as usize];
    let index = ((type_number - 1) * 4 + level_index) as usize;

    let rs_block = RS_BLOCK_TABLE.get(index).unwrap_or(&RS_BLOCK_TABLE[0]);
    let mut list = Vec::new();

    let length = rs_block.len() / 3;
    for i in 0..length {
        let count = rs_block[i * 3];
        let total_count = rs_block[i * 3 + 1];
        let data_count = rs_block[i * 3 + 2];

        for _ in 0..count {
            list.push(QRRSBlock::new(total_count, data_count));
        }
    }

    list
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_get_rs_blocks_v1() {
        let blocks = get_rs_blocks(1, QRErrorCorrectLevel::H);
        assert!(!blocks.is_empty());
    }

    #[test]
    fn test_get_rs_blocks_all_levels() {
        for level in [
            QRErrorCorrectLevel::L,
            QRErrorCorrectLevel::M,
            QRErrorCorrectLevel::Q,
            QRErrorCorrectLevel::H,
        ] {
            let blocks = get_rs_blocks(2, level);
            assert!(
                !blocks.is_empty(),
                "Version 2 {:?} should have blocks",
                level
            );
        }
    }
}
